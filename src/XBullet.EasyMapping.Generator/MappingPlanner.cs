using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace XBullet.EasyMapping.Generator;

internal sealed class MappingPlanner
{
    private readonly Compilation _compilation;
    private readonly INamedTypeSymbol _mapper;
    private readonly CancellationToken _cancellationToken;
    private readonly List<MappingDiagnostic> _diagnostics = [];
    private readonly Dictionary<IMethodSymbol, HashSet<IMethodSymbol>> _dependencies = new(SymbolEqualityComparer.Default);

    public MappingPlanner(Compilation compilation, INamedTypeSymbol mapper, CancellationToken cancellationToken)
    {
        _compilation = compilation;
        _mapper = mapper;
        _cancellationToken = cancellationToken;
    }

    public GeneratedMapper Build()
    {
        _cancellationToken.ThrowIfCancellationRequested();
        var declarations = _mapper.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax(_cancellationToken)).ToArray();
        if (_mapper.TypeKind != TypeKind.Class || _mapper.IsRecord || _mapper.IsFileLocal || _mapper.Arity != 0 || _mapper.ContainingType is not null ||
            declarations.Any(declaration => declaration is not ClassDeclarationSyntax type || !type.Modifiers.Any(SyntaxKind.PartialKeyword)))
        {
            Report(MappingDiagnostics.Mapper, _mapper, "Use a top-level, non-generic partial class without the file modifier for a mapper");
            return Result("");
        }

        var requireSourceCoverage = ReadCoverage();
        var methods = _mapper.GetMembers().OfType<IMethodSymbol>()
            .Where(method => method.MethodKind == MethodKind.Ordinary).ToArray();
        var generated = methods.Where(method => method.IsPartialDefinition && method.PartialImplementationPart is null)
            .OrderBy(method => method.ToDisplayString(), StringComparer.Ordinal).ToArray();
        var bodies = new List<string>();
        foreach (var method in generated)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var body = BuildMethod(method, methods, requireSourceCoverage);
            if (body is not null) { bodies.Add(body); }
        }

        foreach (var method in generated)
        {
            if (HasCycle(method, new HashSet<IMethodSymbol>(SymbolEqualityComparer.Default),
                new HashSet<IMethodSymbol>(SymbolEqualityComparer.Default)))
            {
                Report(MappingDiagnostics.Cycle, method, method.Name);
            }
        }

        if (_diagnostics.Count > 0) { return Result(""); }
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!_mapper.ContainingNamespace.IsGlobalNamespace)
        {
            source.Append("namespace ").Append(_mapper.ContainingNamespace.ToDisplayString()).AppendLine(" {");
        }

        source.Append(_mapper.IsStatic ? "static " : "").Append("partial class ")
            .Append(SymbolNames.Identifier(_mapper.Name)).AppendLine(" {");
        foreach (var body in bodies) { source.AppendLine(body); }
        source.AppendLine("}");
        if (!_mapper.ContainingNamespace.IsGlobalNamespace) { source.AppendLine("}"); }
        return Result(IndentGeneratedSource(source.ToString()), ModelShapeBuilder.Create(_mapper, generated, _cancellationToken));
    }

    private string IndentGeneratedSource(string source)
    {
        var result = new StringBuilder();
        var indent = 0;
        foreach (var rawLine in source.Replace("\r\n", "\n").Split('\n'))
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var line = rawLine.Trim();
            if (line.StartsWith("}", StringComparison.Ordinal) || line.StartsWith(")", StringComparison.Ordinal)) { indent--; }
            if (line.Length > 0) { result.Append(' ', indent * 4).Append(line); }
            result.Append('\n');
            if (line.EndsWith("{", StringComparison.Ordinal) || line.EndsWith("(", StringComparison.Ordinal)) { indent++; }
        }
        return result.ToString();
    }

    private GeneratedMapper Result(string source, ModelApprovalSnapshot? approval = null)
    {
        // Top-level mapper names include their namespace so different namespaces cannot collide.
        var hint = _mapper.ToDisplayString();
        return new GeneratedMapper(hint + ".Mapper.g.cs", source, _diagnostics.ToImmutableArray(), approval);
    }

    private bool ReadCoverage()
    {
        foreach (var attribute in _mapper.GetAttributes().Where(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "XBullet.EasyMapping.MapperAttribute"))
        {
            foreach (var argument in attribute.NamedArguments.Where(argument => argument.Key == "Coverage"))
            {
                if (argument.Value.Value is int value && value is 0 or 1) { return value == 1; }
                Report(MappingDiagnostics.Configuration, _mapper, "Coverage must be MappingCoverage.Target or MappingCoverage.Both");
            }
        }
        return false;
    }

    private string? BuildMethod(IMethodSymbol method, IMethodSymbol[] methods, bool requireSourceCoverage)
    {
        if (method.TypeParameters.Length != 0 || method.IsAbstract || method.IsVirtual || method.IsOverride ||
            method.IsAsync || method.IsExtensionMethod || method.RefKind != RefKind.None ||
            SymbolNames.AccessModifier(method.DeclaredAccessibility).Length == 0 ||
            method.Parameters.Any(parameter => parameter.RefKind != RefKind.None || parameter.IsParams || parameter.IsOptional) ||
            (method.ReturnsVoid ? method.Parameters.Length != 2 : method.Parameters.Length != 1))
        {
            Report(MappingDiagnostics.Signature, method,
                $"Mapping '{method.Name}' must return a DTO from one source, or return void with source and target parameters; generics, ref/out and extension methods are unsupported");
            return null;
        }

        var sourceType = SymbolNames.NonNullable(method.Parameters[0].Type) as INamedTypeSymbol;
        var targetTypeSymbol = method.ReturnsVoid ? method.Parameters[1].Type : method.ReturnType;
        var targetType = SymbolNames.NonNullable(targetTypeSymbol) as INamedTypeSymbol;
        if (sourceType is null || targetType is null || sourceType.TypeKind is not (TypeKind.Class or TypeKind.Struct) ||
            targetType.TypeKind is not (TypeKind.Class or TypeKind.Struct) || targetType.IsAbstract || targetType.IsRefLikeType ||
            sourceType.IsRefLikeType || sourceType.SpecialType != SpecialType.None || targetType.SpecialType != SpecialType.None ||
            ConversionBuilder.TryElement(sourceType, out _) || ConversionBuilder.TryElement(targetType, out _) ||
            (method.ReturnsVoid && (targetType.IsValueType || SymbolNames.IsNullable(targetTypeSymbol))))
        {
            Report(MappingDiagnostics.Signature, method,
                $"Mapping '{method.Name}' requires DTO roots; updates require a non-nullable class target");
            return null;
        }

        var sourceProperties = SymbolNames.Properties(sourceType).Where(property => !property.IsIndexer &&
            property.GetMethod?.DeclaredAccessibility == Accessibility.Public).ToArray();
        var targetProperties = SymbolNames.Properties(targetType);
        if (requireSourceCoverage)
        {
            for (var current = sourceType; current is not null; current = current.BaseType)
            {
                if (current.GetMembers().OfType<IFieldSymbol>().Any(field => !field.IsStatic && field.DeclaredAccessibility == Accessibility.Public))
                {
                    Report(MappingDiagnostics.Target, method, "Public source fields are unsupported with strict source coverage; use properties");
                    break;
                }
            }
            if (SymbolNames.Properties(sourceType).Any(property => property.IsIndexer))
            {
                Report(MappingDiagnostics.Target, method, "Source indexers are unsupported with strict source coverage");
            }
        }
        if (sourceProperties.GroupBy(property => property.Name, StringComparer.OrdinalIgnoreCase).Any(group => group.Count() > 1) ||
            targetProperties.GroupBy(property => property.Name, StringComparer.OrdinalIgnoreCase).Any(group => group.Count() > 1))
        {
            Report(MappingDiagnostics.Configuration, method, "DTO property names must be unique when compared without case");
        }
        var renames = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var ignores = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        ReadConfiguration(method, sourceProperties, targetType, targetProperties, renames, ignores);
        var sourceCoverage = new SourceCoverageValidator(sourceProperties.Select(property => property.Name).ToArray(),
            method, requireSourceCoverage, (descriptor, arguments) => Report(descriptor, method, arguments));
        var conversion = new ConversionBuilder(_compilation, method, methods,
            (descriptor, arguments) => Report(descriptor, method, arguments));
        _dependencies.Add(method, conversion.Dependencies);
        var sourceName = SymbolNames.Identifier(method.Parameters[0].Name);
        var body = new StringBuilder();
        var declaration = (MethodDeclarationSyntax)method.DeclaringSyntaxReferences[0].GetSyntax(_cancellationToken);
        var hasAccessModifier = declaration.Modifiers.Any(token => token.IsKind(SyntaxKind.PublicKeyword) ||
            token.IsKind(SyntaxKind.PrivateKeyword) || token.IsKind(SyntaxKind.InternalKeyword));
        body.Append(hasAccessModifier ? SymbolNames.AccessModifier(method.DeclaredAccessibility) : "").Append(method.IsStatic ? " static" : "")
            .Append(" partial ").Append(method.ReturnsVoid ? "void" : SymbolNames.Type(method.ReturnType)).Append(' ')
            .Append(SymbolNames.Identifier(method.Name)).Append('(')
            .Append(string.Join(", ", method.Parameters.Select(parameter =>
                SymbolNames.Type(parameter.Type) + " " + SymbolNames.Identifier(parameter.Name)))).AppendLine(") {");

        if (method.Parameters[0].Type.IsReferenceType || SymbolNames.IsNullable(method.Parameters[0].Type))
        {
            if (!method.ReturnsVoid && SymbolNames.IsNullable(method.Parameters[0].Type) && SymbolNames.IsNullable(method.ReturnType))
            {
                body.Append("if (").Append(sourceName).AppendLine(" is null) return default;");
            }
            else
            {
                Guard(body, sourceName, method.Parameters[0].Name);
            }
        }

        if (method.Parameters[0].Type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T })
        {
            var local = conversion.NewName();
            body.Append("var ").Append(local).Append(" = ").Append(sourceName).AppendLine(".Value;");
            sourceName = local;
        }

        if (method.ReturnsVoid)
        {
            var targetName = SymbolNames.Identifier(method.Parameters[1].Name);
            Guard(body, targetName, method.Parameters[1].Name);
            BuildProperties(body, method, sourceProperties, targetProperties, renames, ignores, conversion, sourceName,
                targetName, new HashSet<string>(StringComparer.OrdinalIgnoreCase), constructorSetsRequired: false, sourceCoverage);
        }
        else
        {
            var constructor = SelectConstructor(method, targetType, sourceProperties, renames, ignores);
            if (constructor is null) { return null; }
            var usedNames = new HashSet<string>(targetProperties.Select(property => property.Name), StringComparer.OrdinalIgnoreCase);
            usedNames.UnionWith(constructor.Parameters.Select(parameter => parameter.Name));
            foreach (var configuredName in renames.Keys.Concat(ignores).Where(name => !usedNames.Contains(name)))
            {
                Report(MappingDiagnostics.Configuration, method, $"Configured target '{configuredName}' is not used by the selected constructor or properties");
            }
            var arguments = new List<string>();
            var consumed = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var parameter in constructor.Parameters)
            {
                var property = FindSource(parameter.Name, sourceProperties, renames);
                if (property is null || ignores.Contains(parameter.Name)) { continue; }
                consumed.Add(parameter.Name);
                sourceCoverage.RecordMapped(property.Name);
                arguments.Add(SymbolNames.Identifier(parameter.Name) + ": " + conversion.Convert(property.Type,
                    parameter.Type, sourceName + "." + SymbolNames.Identifier(property.Name), parameter.Name));
            }

            body.Append("return new ").Append(SymbolNames.Type(targetType)).AppendLine("(")
                .AppendLine(string.Join(",\n", arguments)).AppendLine(") {");
            var setsRequired = constructor.GetAttributes().Any(attribute =>
                attribute.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.SetsRequiredMembersAttribute");
            BuildProperties(body, method, sourceProperties, targetProperties, renames, ignores, conversion, sourceName,
                null, consumed, setsRequired, sourceCoverage);
            body.AppendLine("};");
        }

        sourceCoverage.Validate();
        foreach (var helper in conversion.CollectionHelpers) { body.AppendLine(helper); }
        body.AppendLine("}");
        return body.ToString();
    }

    private void BuildProperties(StringBuilder body, IMethodSymbol method, IPropertySymbol[] sourceProperties,
        IPropertySymbol[] targetProperties, Dictionary<string, string> renames, HashSet<string> ignores,
        ConversionBuilder conversion, string sourceName, string? targetName, HashSet<string> consumed, bool constructorSetsRequired,
        SourceCoverageValidator sourceCoverage)
    {
        foreach (var target in targetProperties)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            if (ignores.Contains(target.Name))
            {
                if (!method.ReturnsVoid && target.IsRequired && !constructorSetsRequired)
                {
                    Report(MappingDiagnostics.Configuration, method, $"Cannot ignore required target property '{target.Name}'");
                }
                continue;
            }

            if (target.IsIndexer)
            {
                Report(MappingDiagnostics.Target, method, "Target indexers are unsupported; use named properties");
                continue;
            }

            if (consumed.Contains(target.Name) && (!target.IsRequired || constructorSetsRequired)) { continue; }
            var source = FindSource(target.Name, sourceProperties, renames);
            if (source is null)
            {
                Report(MappingDiagnostics.MissingSource, method, target.Name, method.Name);
                continue;
            }

            if (target.SetMethod?.DeclaredAccessibility != Accessibility.Public ||
                (method.ReturnsVoid && target.SetMethod.IsInitOnly))
            {
                Report(MappingDiagnostics.Target, method,
                    $"Target property '{target.Name}' is not writable in this mapping; map it through a constructor or explicitly ignore it");
                continue;
            }

            var expression = conversion.Convert(source.Type, target.Type,
                sourceName + "." + SymbolNames.Identifier(source.Name), target.Name);
            sourceCoverage.RecordMapped(source.Name);
            body.Append(targetName is null ? "" : targetName + ".").Append(SymbolNames.Identifier(target.Name))
                .Append(" = ").Append(expression).AppendLine(targetName is null ? "," : ";");
        }
    }

    private IMethodSymbol? SelectConstructor(IMethodSymbol method, INamedTypeSymbol target, IPropertySymbol[] source,
        Dictionary<string, string> renames, HashSet<string> ignores)
    {
        var viable = target.InstanceConstructors.Where(constructor => constructor.DeclaredAccessibility == Accessibility.Public &&
            constructor.Parameters.All(parameter => parameter.RefKind == RefKind.None &&
                (parameter.IsOptional || (!ignores.Contains(parameter.Name) && FindSource(parameter.Name, source, renames) is not null))))
            .ToArray();
        var parameterless = viable.FirstOrDefault(constructor => constructor.Parameters.Length == 0);
        if (parameterless is not null) { return parameterless; }
        if (viable.Length == 1) { return viable[0]; }
        Report(MappingDiagnostics.Constructor, method, viable.Length == 0
            ? $"Target '{target.Name}' has no public constructor with mappable parameters"
            : $"Target '{target.Name}' has multiple mappable constructors and no public parameterless constructor");
        return null;
    }

    private void ReadConfiguration(IMethodSymbol method, IPropertySymbol[] source, INamedTypeSymbol target,
        IPropertySymbol[] properties, Dictionary<string, string> renames, HashSet<string> ignores)
    {
        var targetNames = new HashSet<string>(properties.Select(property => property.Name), StringComparer.OrdinalIgnoreCase);
        if (!method.ReturnsVoid)
        {
            targetNames.UnionWith(target.InstanceConstructors.Where(constructor => constructor.DeclaredAccessibility == Accessibility.Public)
                .SelectMany(constructor => constructor.Parameters.Select(parameter => parameter.Name)));
        }
        foreach (var attribute in method.GetAttributes())
        {
            var name = attribute.AttributeClass?.ToDisplayString();
            if (name == "XBullet.EasyMapping.MapPropertyAttribute")
            {
                if (attribute.ConstructorArguments.Length != 2)
                {
                    Report(MappingDiagnostics.Configuration, method, "MapProperty requires source and target names");
                    continue;
                }
                var sourceName = attribute.ConstructorArguments[0].Value as string;
                var targetName = attribute.ConstructorArguments[1].Value as string;
                if (sourceName is null || targetName is null || !source.Any(property => property.Name == sourceName) ||
                    !targetNames.Contains(targetName) || renames.ContainsKey(targetName))
                {
                    Report(MappingDiagnostics.Configuration, method, "MapProperty requires existing source/target names and one configuration per target");
                }
                else { renames.Add(targetName, sourceName); }
            }
            else if (name == "XBullet.EasyMapping.MapIgnoreTargetAttribute")
            {
                if (attribute.ConstructorArguments.Length != 1)
                {
                    Report(MappingDiagnostics.Configuration, method, "MapIgnoreTarget requires a target name");
                    continue;
                }
                var targetName = attribute.ConstructorArguments[0].Value as string;
                if (targetName is null || !targetNames.Contains(targetName) || !ignores.Add(targetName))
                {
                    Report(MappingDiagnostics.Configuration, method, "MapIgnoreTarget requires an existing target and cannot be repeated");
                }
            }
        }

        foreach (var name in renames.Keys.Where(ignores.Contains))
        {
            Report(MappingDiagnostics.Configuration, method, $"Target '{name}' cannot be both mapped and ignored");
        }

        for (var current = target; current is not null; current = current.BaseType)
        {
            if (current.GetMembers().OfType<IFieldSymbol>().Any(field => !field.IsStatic && field.DeclaredAccessibility == Accessibility.Public))
            {
                Report(MappingDiagnostics.Target, method, "Public target fields are unsupported; use properties");
                break;
            }
        }
    }

    private static IPropertySymbol? FindSource(string targetName, IPropertySymbol[] source, Dictionary<string, string> renames)
    {
        if (renames.TryGetValue(targetName, out var sourceName)) { return source.FirstOrDefault(property => property.Name == sourceName); }
        return source.FirstOrDefault(property => property.Name == targetName) ??
            source.FirstOrDefault(property => string.Equals(property.Name, targetName, StringComparison.OrdinalIgnoreCase));
    }

    private bool HasCycle(IMethodSymbol method, HashSet<IMethodSymbol> visiting, HashSet<IMethodSymbol> visited)
    {
        _cancellationToken.ThrowIfCancellationRequested();
        if (!visiting.Add(method)) { return true; }
        if (visited.Add(method) && _dependencies.TryGetValue(method, out var dependencies) &&
            dependencies.Any(dependency => HasCycle(dependency, visiting, visited))) { return true; }
        visiting.Remove(method);
        return false;
    }

    private void Report(DiagnosticDescriptor descriptor, ISymbol symbol, params string[] arguments) =>
        _diagnostics.Add(new MappingDiagnostic(descriptor, symbol.Locations.First(location => location.IsInSource), arguments));

    private static void Guard(StringBuilder body, string expression, string name) => body.Append("if (").Append(expression)
        .Append(" is null) throw new global::System.ArgumentNullException(\"").Append(name).AppendLine("\");");
}
