using System.Text;

namespace XBullet.EasyMapping.Generator;

internal sealed class ModelApprovalSnapshot : IEquatable<ModelApprovalSnapshot>
{
    public const string Suffix = ".mapper.approved.txt";
    public const string StartMarker = "// <MapperModelApproval>";
    public const string EndMarker = "// </MapperModelApproval>";
    public const string SourcePathMarker = "// MapperSourcePath: ";

    public ModelApprovalSnapshot(string mapperName, string content, MappingDiagnostic diagnostic, string sourcePath)
    {
        FileName = mapperName + Suffix;
        SourceHint = mapperName + ".ModelApproval.g.cs";
        Content = Normalize(content);
        Diagnostic = diagnostic;
        SourcePath = sourcePath;
    }

    public string FileName
    {
        get;
    }
    public string SourceHint
    {
        get;
    }
    public string Content
    {
        get;
    }
    public MappingDiagnostic Diagnostic
    {
        get;
    }
    public string SourcePath
    {
        get;
    }

    public string GenerateSource()
    {
        var source = new StringBuilder("// <auto-generated/>\n// Review before explicitly approving this snapshot.\n");
        // Paths are transport metadata, never part of the portable approved model shape.
        source.Append(SourcePathMarker).Append(Convert.ToBase64String(Encoding.UTF8.GetBytes(SourcePath))).Append('\n');
        source.Append(StartMarker).Append('\n');
        foreach (var line in Content.TrimEnd('\n').Split('\n'))
        {
            source.Append("// ").Append(line).Append('\n');
        }

        return source.Append(EndMarker).Append('\n').ToString();
    }

    public static string Normalize(string content) => content.Replace("\r\n", "\n").TrimEnd('\n') + "\n";

    public bool Equals(ModelApprovalSnapshot? other) => other is not null && FileName == other.FileName &&
        Content == other.Content && SourcePath == other.SourcePath && Diagnostic.Equals(other.Diagnostic);

    public override bool Equals(object? obj) => Equals(obj as ModelApprovalSnapshot);
    public override int GetHashCode() => FileName.GetHashCode();
}
